def _step_curves(key, pre=30, post=300):
    d = np.load(OUTPUTS / f"e2_refstep/{key}_m1337.npz")
    ref, cut = d["reference_y"][:, :, 0], d["cutter_y"][:, :, 0]
    segs = []
    for e in range(ref.shape[1]):
        dr = np.diff(ref[:, e])
        k = int(np.argmax(np.abs(dr))) + 1
        step = float(dr[k - 1])
        if abs(step) < 0.05 or k < pre or k + post >= len(ref):
            continue
        base = ref[:, e].copy()
        base[k:] -= step                     # subtract the underlying trajectory
        y = cut[:, e] - base
        y = y - y[k - pre:k].mean()
        segs.append(y[k - pre:k + post] / step)
    return np.array(segs)


