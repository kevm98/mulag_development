def _flip_window(suffix="_early"):
    """Environments whose own flip instant leaves W steps on both sides.

    The naive pre/post split confounds the load change with episode phase, so
    each environment is aligned on its own flip and the same environment set is
    used for every arm, which keeps the arms paired.
    """
    ap = np.load(PRESS / f"af_base_m1337{suffix}.npz")["theta_mass_step_applied"][:, :, 0]
    T, N = ap.shape
    flip = np.array([np.argmax(ap[:, i] > 0.5) if ap[-1, i] > 0.5 else -1
                     for i in range(N)])
    for name, *_ in ARMS:
        b = np.load(PRESS / f"{name}_m1337{suffix}.npz")["theta_mass_step_applied"][:, :, 0]
        f = np.array([np.argmax(b[:, i] > 0.5) if b[-1, i] > 0.5 else -1
                      for i in range(N)])
        if not (f == flip).all():
            raise SystemExit(f"{name} has a different flip schedule; pairing void")
    keep = np.where((flip >= W) & (flip <= T - W))[0]
    return flip, keep, N


def _aligned(arr, flip, keep):
    """(env, 2W, ...) stack of each environment's own window about its flip."""
    return np.stack([arr[flip[i] - W:flip[i] + W, i] for i in keep])


def fig_af_arms():
    """The three residual arms through the change of load."""
    flip, keep, N = _flip_window()
    t = np.arange(-W, W) / FS
    fig, axes = plt.subplots(1, 2, figsize=(FULLW, 2.75), sharex=True)
    panels = [("lateral_error", "(a) lateral error"),
              ("cut_height_error", "(b) cut-height error")]
    for ax, (key, title) in zip(axes, panels):
        for name, label, col, ls in ARMS:
            d = np.load(PRESS / f"{name}_m1337_early.npz")
            v = np.abs(d[key][:, :, 0])
            al = _aligned(v, flip, keep)                 # (env, 2W)
            # Mean over environments, which is the estimand the arms table
            # reports. The median of an absolute error sits near zero on cut
            # height and would draw three flat lines.
            m = 1000 * np.mean(al, axis=0)
            ax.plot(t, _roll(m, 21), color=col, lw=1.5, label=label, ls=ls)
        ax.axvline(0, color=C_RED, lw=1.0, ls="--")
        ax.set_xlim(t[0], t[-1])
        ax.set_xlabel("time relative to the change of load (s)")
        ax.set_ylabel("mean absolute error (mm)")
        ax.grid(True)
        ax.set_title(title, loc="left")
    axes[1].annotate("load change", (0, axes[1].get_ylim()[1]), xytext=(4, -4),
                     textcoords="offset points", va="top", fontsize=7.4,
                     color=C_RED)
    h, l = axes[0].get_legend_handles_labels()
    fig.legend(h, l, ncol=3, loc="upper center", bbox_to_anchor=(.5, 1.0),
               fontsize=8, frameon=False, columnspacing=1.8, handlelength=1.9)
    fig.subplots_adjust(left=.095, right=.985, top=.815, bottom=.165, wspace=.30)
    save(fig, "ch7_af_arms")
    print(f"     {len(keep)} of {N} environments usable both sides of the flip")


def fig_pressure_stacks():
    """Median differential pressure per cylinder, all three stacks.

    The quantity is each stack's own actuator-model state, so the panels show
    what each controller believes about the hydraulics rather than a common
    measurement. Absolute levels are therefore not comparable across stacks;
    the shape either side of the change is.
    """
    flip, keep, N = _flip_window()
    t = np.arange(-W, W) / FS
    files = {"ppo_rom": "rom", "ppo_id_fd": "idfd", "ppo_aam_id_fd": "af_adaptive"}
    fig, axes = plt.subplots(1, 4, figsize=(FULLW, 2.5))
    CLIP = 1500.0                       # numerical guard in the command ROM
    for c, ax in enumerate(axes):
        clipped = []
        for key, label, col in STACKS:
            dp = np.load(PRESS / f"{files[key]}_m1337_early.npz")["chain_dP"] / 1e5
            al = _aligned(dp[:, :, c], flip, keep)
            med = np.median(al, axis=0)
            ax.plot(t, med, color=col, lw=1.3, label=label)
            if np.mean(np.abs(np.abs(dp[:, :, c]) - CLIP) < 1e-3) > 0.01:
                clipped.append(label)
        for s in (+1, -1):
            ax.axhline(s * 340, color=C_RULE, lw=.8, ls=":")
        ax.axvline(0, color=C_RED, lw=1.0, ls="--")
        ax.set_xlim(t[0], t[-1])
        ax.set_xticks([-4, 0, 4])
        ax.set_xlabel("time (s)")
        ax.grid(True, axis="y")
        ax.set_title(f"({'abcd'[c]}) {CYLINDERS[c]}", loc="left", fontsize=8.2)
        if clipped:
            ax.annotate("ROM on its\n$\\pm$1500 bar guard",
                        xy=(0.04, 0.04), xycoords="axes fraction", fontsize=6.5,
                        color=C_RED, va="bottom")
    axes[0].set_ylabel(r"median $\Delta p$ (bar)")
    h, l = axes[0].get_legend_handles_labels()
    h.append(plt.Line2D([], [], color=C_RULE, lw=.8, ls=":"))
    l.append("$\\pm$340 bar nominal supply")
    fig.legend(h, l, ncol=4, loc="upper center", bbox_to_anchor=(.5, 1.0),
               fontsize=7.6, frameon=False, columnspacing=1.5, handlelength=1.7)
    # The per-panel scaling is stated in the caption; repeating it here at 6.8pt
    # only adds a line of type too small to read.
    fig.subplots_adjust(left=.095, right=.99, top=.80, bottom=.20, wspace=.42)
    save(fig, "ch7_pressure_stacks")


