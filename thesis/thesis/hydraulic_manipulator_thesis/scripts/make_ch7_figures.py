def load_seeds():
    """Five matched training seeds: no-latent baseline, latent model, and the
    two substitution modes scored on the latent model."""
    seeds, base, e2e, tvar, ident, const, wrong = [], [], [], [], [], [], []
    for p in sorted((OPENLOOP / "seeds").glob("sd_none_s*/metrics.json")):
        s = p.parent.name.split("_s")[-1]
        q = OPENLOOP / f"seeds/e2e_s{s}/metrics.json"
        abl = OPENLOOP / f"seeds/e2e_s{s}/latent_ablation.json"
        if not (q.is_file() and abl.is_file()):
            continue
        m = load(abl)["modes"]
        seeds.append(s)
        base.append(load(p)["best_val_loss"])
        e2e.append(load(q)["val_rollout_state_mse"])
        const.append(m["run_mean"]["val"])
        wrong.append(m["shuffled"]["val"])
        tvar.append(100 * (m["run_mean"]["val"] / m["online"]["val"] - 1))
        ident.append(100 * (m["shuffled"]["val"] / m["run_mean"]["val"] - 1))
    return (seeds, np.array(base), np.array(e2e), np.array(tvar),
            np.array(ident), np.array(const), np.array(wrong))


