def fig_chain_by_stack():
    """Closed-loop chain latency, matched pair.

    Cross-correlation lag, not onset: a closed-loop command has no step edges.
    Valid for comparing stacks, where the bias is identical, and not comparable
    with the open-loop dead times.
    """
    d = load(EXP / "E2/results/chain_delay_by_stack.json")["stacks"]
    links = ["command $\\to$ pressure", "pressure $\\to$ cyl. velocity",
             "command $\\to$ cyl. velocity", "cyl. velocity $\\to$ joint velocity"]
    nice = ["command $\\rightarrow$ pressure", "pressure $\\rightarrow$ cyl. velocity",
            "command $\\rightarrow$ cyl. velocity",
            "cyl. velocity $\\rightarrow$ joint velocity"]
    fig, ax = plt.subplots(figsize=(FULLW * 0.92, 2.9))
    y = np.arange(len(links))
    h = 0.3
    step_ms = 1000.0 / FS
    # The mechanical link is the control: a static linkage cannot delay, so the
    # row must read the resolution floor of one control step. Shade that row and
    # say what the floor is, rather than claiming it must read zero.
    ax.axhspan(len(links) - 1 - 0.5, len(links) - 1 + 0.5, color="#EDF1F4", lw=0,
               zorder=0)
    for i, (s, label, col) in enumerate(PAIR):
        vals = [d[FULL[s]][k]["median_ms"] for k in links]
        ax.barh(y + (i - 0.5) * h, vals, height=h * 0.88, color=col, alpha=.92,
                label=label, zorder=2)
        for j, v in enumerate(vals):
            ax.annotate(f"{v:.0f}", (v, y[j] + (i - 0.5) * h), xytext=(4, 0),
                        textcoords="offset points", va="center", fontsize=7.8,
                        color=col, zorder=3)
    ax.axvline(step_ms, color=C_RULE, lw=1.0, ls=":", zorder=1)
    ax.annotate("control: cylinder and joint are coupled by a static linkage,\n"
                "so this row must read the resolution floor of one control step",
                xy=(0.985, len(links) - 1 + 0.02), xycoords=("axes fraction", "data"),
                ha="right", va="center", fontsize=7.2, color=C_RULE)
    ax.set_yticks(y)
    ax.set_yticklabels(nice, fontsize=8.6)
    ax.invert_yaxis()
    ax.set_xlim(0, 520)
    ax.set_xlabel("cross-correlation lag (ms)")
    ax.grid(axis="x")
    ax.set_ylim(len(links) - 0.45, -1.05)
    ax.legend(fontsize=8, loc="upper right", ncol=2, columnspacing=1.2,
              handletextpad=.4)
    fig.subplots_adjust(left=.30, right=.985, top=.965, bottom=.17)
    save(fig, "ch7_chain_by_stack")


def _step_curves(key, pre=30, post=300):
    d = np.load(OUTPUTS / f"e2_refstep/{key}_m1337.npz")
    ref, cut = d["reference_y"][:, :, 0], d["cutter_y"][:, :, 0]
    segs = []
    for e in range(ref.shape[1]):
        dr = np.diff(ref[:, e])
        k = int(np.argmax(np.abs(dr))) + 1
        step = float(dr[k - 1])
        if abs(step) < 0.05 or k < pre or k + post >= len(ref):
            continue
        base = ref[:, e].copy()
        base[k:] -= step                     # subtract the underlying trajectory
        y = cut[:, e] - base
        y = y - y[k - pre:k].mean()
        segs.append(y[k - pre:k + post] / step)
    return np.array(segs)


