def _flip_window(suffix="_early"):
    """Environments whose own flip instant leaves W steps on both sides.

    The naive pre/post split confounds the load change with episode phase, so
    each environment is aligned on its own flip and the same environment set is
    used for every arm, which keeps the arms paired.
    """
    ap = np.load(PRESS / f"af_base_m1337{suffix}.npz")["theta_mass_step_applied"][:, :, 0]
    T, N = ap.shape
    flip = np.array([np.argmax(ap[:, i] > 0.5) if ap[-1, i] > 0.5 else -1
                     for i in range(N)])
    for name, *_ in ARMS:
        b = np.load(PRESS / f"{name}_m1337{suffix}.npz")["theta_mass_step_applied"][:, :, 0]
        f = np.array([np.argmax(b[:, i] > 0.5) if b[-1, i] > 0.5 else -1
                      for i in range(N)])
        if not (f == flip).all():
            raise SystemExit(f"{name} has a different flip schedule; pairing void")
    keep = np.where((flip >= W) & (flip <= T - W))[0]
    return flip, keep, N


def _aligned(arr, flip, keep):
    """(env, 2W, ...) stack of each environment's own window about its flip."""
    return np.stack([arr[flip[i] - W:flip[i] + W, i] for i in keep])


