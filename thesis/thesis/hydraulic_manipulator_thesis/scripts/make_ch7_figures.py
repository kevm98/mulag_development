def fig_delay_response(amp=0.15):
    """When each stage of the chain actually starts moving, on one time axis.

    A normalised step response answers "what does the pressure do", not the
    question the section asks, which is "how long until each thing happens".
    This is that question drawn literally: the command edge is the origin, each
    downstream stage sits at its measured onset, and the bar beside it is the
    interquartile spread over command edges.
    """
    delays = load(OPENLOOP / "transport_delay.json")["links"]
    key = f"{amp}"
    chain = [("valve command", None, "#111111"),
             ("differential pressure", "command->dP", C_BLUE),
             ("cylinder extension", "command->cyl_ext", C_GREEN),
             ("joint angle", "command->joint_pos", C_PINK),
             ("cylinder velocity", "command->cyl_vel", C_ORANGE)]

    fig, ax = plt.subplots(figsize=(FULLW * 0.86, 2.95))
    xmax = 0.0
    for i, (label, k, col) in enumerate(chain):
        if k is None:
            ax.plot([0], [i], "|", ms=16, color=col, mew=2.4, zorder=4)
            ax.annotate("edge at $t = 0$", (0, i), xytext=(9, 0),
                        textcoords="offset points", va="center", fontsize=8.4)
            continue
        rec = delays[k][key]
        med = rec["median_ms"]
        q1, q3 = np.array(rec["iqr_steps"]) * 1000.0 / FS
        xmax = max(xmax, q3)
        ax.plot([0, med], [i, i], color=col, lw=6.5, alpha=.22,
                solid_capstyle="butt", zorder=1)
        ax.plot([q1, q3], [i, i], color=col, lw=2.0, zorder=3,
                solid_capstyle="round")
        ax.plot([med], [i], "o", ms=8.5, color=col, mec="white", mew=1.1,
                zorder=5)
        ax.annotate(f"{med:.0f} ms", (med, i), xytext=(0, 11),
                    textcoords="offset points", ha="center", fontsize=8.6,
                    color=col)
    ax.axvline(0, color="#111111", lw=1.3, zorder=2)
    ax.set_yticks(np.arange(len(chain)))
    ax.set_yticklabels([c[0] for c in chain], fontsize=9)
    ax.invert_yaxis()
    ax.set_xlim(-18, xmax * 1.10)
    ax.set_ylim(len(chain) - 0.30, -0.60)
    ax.set_xlabel("time after the valve command changes (ms)")
    ax.grid(axis="x")
    # Its own band below the last row. An annotation that hangs off the canvas,
    # or lands on a data row, is worse than none; both happened earlier.
    ax.annotate("shaded: the wait before that stage moves    "
                "bar: interquartile range over command edges",
                xy=(xmax * 1.08, len(chain) - 0.52), ha="right", va="center",
                fontsize=7.2, color="#6B7780")
    fig.subplots_adjust(left=.235, right=.98, top=.965, bottom=.185)
    save(fig, "ch7_delay_response")


