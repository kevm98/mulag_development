def load_seeds():
    """Five matched training seeds: no-latent baseline, latent model, and the
    two substitution modes scored on the latent model."""
    seeds, base, e2e, tvar, ident, const, wrong = [], [], [], [], [], [], []
    for p in sorted((OPENLOOP / "seeds").glob("sd_none_s*/metrics.json")):
        s = p.parent.name.split("_s")[-1]
        q = OPENLOOP / f"seeds/e2e_s{s}/metrics.json"
        abl = OPENLOOP / f"seeds/e2e_s{s}/latent_ablation.json"
