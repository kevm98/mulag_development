TRACES = OUTPUTS / "e1_traces"

# The environment loop assigns TRACKING_PATH_FAMILIES[(env + 0) % 11], so the
# mapping is deterministic. It is asserted rather than assumed: per-environment
# errors are re-aggregated into per-family means and checked against the run's
# own gate report. An earlier figure mislabelled its panels by matching on error
# value alone, which is worse than having no figure.
FAMILIES = ("straight", "lateral_sine", "s_curve", "random_spline",
            "offset_return", "boom_sweep", "lateral_chirp", "double_s_curve",
            "lane_change_hold", "gaussian_slalom", "fourier_meander")


def _trace(stack):
    d = np.load(TRACES / f"{stack}_m1337.npz")
    g = lambda k: d[k][:, :, 0]
    rep = load(TRACES / f"{stack}_m1337.json")["per_mesh"]["1337"]
    fam = {f["family"]: f["mean_abs_lateral_error_m"]
           for f in rep["path_family_results"]}
    famcut = {f["family"]: f["mean_abs_cut_height_error_m"]
              for f in rep["path_family_results"]}
    # The vertical reference is not recorded but is recoverable: cut-height
    # error is the signed difference between the cutter and the height it should
    # be holding, so z_ref = z_cutter - e_cut. That makes the right column a
    # like-for-like reference-versus-actual plot rather than a bare trace.
    return dict(x=g("cutter_x"), y=g("cutter_y"), ref=g("reference_y"),
                z=g("cutter_z"), refz=g("cutter_z") - g("cut_height_error"),
                lat=g("lateral_error"), cut=g("cut_height_error"), fam=fam,
                famcut=famcut)


def _family_envs(D, tol=2e-3):
    ref = D["ppo_rom"]
    per_env = np.abs(ref["lat"]).mean(0)
    n_env = per_env.size
    assign = {i: FAMILIES[i % len(FAMILIES)] for i in range(n_env)}
    for fam, reported in ref["fam"].items():
        envs = [i for i in range(n_env) if assign[i] == fam]
        got = float(np.mean([per_env[i] for i in envs]))
        if abs(got - reported) > tol:
            raise SystemExit(
                f"family mapping failed its own check: {fam} re-aggregates to "
                f"{got:.4f} from envs {envs}, report says {reported:.4f}")
    return {FAMILIES[i % len(FAMILIES)]: i for i in range(len(FAMILIES))}


def _roll(a, k):
    """Centred moving average with the edges held, so the curve does not dip."""
    if k < 2:
        return a
    pad = k // 2
    ext = np.concatenate([np.full(pad, a[0]), a, np.full(pad, a[-1])])
    return np.convolve(ext, np.ones(k) / k, mode="valid")[:a.size]


def fig_e1_paths(smooth=150, half=0.62, lw=2.0):
    """Reference against tracked path on the three best-tracked families.

    Only the matched pair is drawn. The adaptive stack's cross-stack traces
    were taken before its command path was rebuilt (Section 7.1.3), so they
    describe a controller that is no longer deployed.
    """
    D = {s: _trace(s) for s, _, _ in PAIR}
    f2e = _family_envs(D)
    # Three well-tracked families that are structurally different from one
    # another: a flat line, a smooth periodic sweep, a step-and-hold. The
    # Gaussian slalom scores marginally better than the lane change but its
    # reference is visually a sine, so its panel would repeat the one above it.
    best = ["straight", "lateral_sine", "lane_change_hold"]
    # The chapter's stack colours: R is red, IF is green, here lightened so the
    # wider red trace stays readable beneath it. The wide trace is drawn first
    # and the narrow one second, so both remain visible where the paths nearly
    # coincide. The reference stays neutral and dashed.
    path_style = {
        "ppo_rom": dict(label="R (PPO-ROM)", color=C_RED, width=2.6),
        "ppo_id_fd": dict(label="IF (PPO-ID-FD)", color="#6ABF69", width=1.8),
    }
    reference_color = "#3F464D"

    fig, axes = plt.subplots(len(best), 2, figsize=(FULLW, 1.85 * len(best) + 1.0),
                             sharex=True)
    for r, f in enumerate(best):
        env = f2e[f]
        ref = D["ppo_rom"]
        o = np.argsort(ref["x"][:, env])
        xs = ref["x"][o, env] - ref["x"][:, env].min()
        axL, axR = axes[r, 0], axes[r, 1]
        axL.plot(xs, ref["ref"][o, env], color=reference_color, lw=1.6,
                 ls=(0, (5, 2.5)), label="reference", zorder=6)
        axR.plot(xs, _roll(ref["refz"][o, env], smooth),
                 color=reference_color, lw=1.6, ls=(0, (5, 2.5)),
                 label="reference", zorder=6)
        for i, (st, _, _) in enumerate(PAIR):
            d = D[st]
            oi = np.argsort(d["x"][:, env])
            xx = d["x"][oi, env] - d["x"][:, env].min()
            style = path_style[st]
            axL.plot(xx, _roll(d["y"][oi, env], smooth),
                     color=style["color"], lw=style["width"],
                     label=style["label"], zorder=3 + i,
                     solid_capstyle="round")
            axR.plot(xx, _roll(d["z"][oi, env], smooth),
                     color=style["color"], lw=style["width"],
                     label=style["label"], zorder=3 + i,
                     solid_capstyle="round")
        midy = float(np.median(ref["ref"][o, env]))
        midz = float(np.median(ref["refz"][o, env]))
        axL.set_ylim(midy - half, midy + half)
        axR.set_ylim(midz - 0.34, midz + 0.34)
        # The family's own reported error over the matched pair, not this one
        # environment's: the panel draws a representative environment but the
        # number quoted must be the one the tables and the caption use.
        lat = np.mean([D[s]["fam"][f] for s, _, _ in PAIR])
        cut = np.mean([D[s]["famcut"][f] for s, _, _ in PAIR])
        axL.set_ylabel("lateral (m)")
        axR.set_ylabel("height (m)")
        for a in (axL, axR):
            a.set_axisbelow(True)
            a.grid(True, color="#D5DADF", linewidth=.45, alpha=.65)
            for spine in a.spines.values():
                spine.set_color("#7C8791")
        name = f.replace("_", " ")
        axL.set_title(f"({'abc'[r]}) {name}: horizontal "
                      f"(lateral {lat*1000:.0f} mm)", loc="left", fontsize=8.6)
        axR.set_title(f"{name}: vertical (cut height {cut*1000:.0f} mm)",
                      loc="left", fontsize=8.6)

    for c in (0, 1):
        axes[-1, c].set_xlabel("travel along the verge (m)")
    h, l = axes[0, 0].get_legend_handles_labels()
    fig.legend(h, l, ncol=3, loc="upper center", bbox_to_anchor=(.5, 1.0),
               columnspacing=1.8, handlelength=2.2, fontsize=9, frameon=False)

    # A scale bar lets the reader size a deviation without a magnification
    # factor being quoted anywhere.
    x_lo, x_hi = axes[0, 0].get_xlim()
    y_lo, y_hi = axes[0, 0].get_ylim()
    xb = x_lo + 0.035 * (x_hi - x_lo)
    yb = y_lo + 0.09 * (y_hi - y_lo)
    axes[0, 0].plot([xb, xb], [yb, yb + 0.10], color="#111111", lw=2.2,
                    solid_capstyle="butt", zorder=8)
    axes[0, 0].annotate("100 mm", (xb, yb + 0.05), xytext=(5, 0),
                        textcoords="offset points", va="center", fontsize=7.5)
    fig.subplots_adjust(left=.085, right=.985, top=.905, bottom=.075,
                        hspace=.40, wspace=.26)
    save(fig, "ch7_e1_paths")


def fig_e1_tracking():
    """(a) error by family, easiest first; (b) the paired matched-pair contrast.

    A pooled box plot hid the thing that matters, which is WHICH trajectories
    separate the stacks: two families are an order of magnitude harder than the
    rest and are what carry the pooled means.
    """
    per = {s: e1_family_means(s) for s, _, _ in PAIR}
    fams = sorted(per["ppo_rom"])
    order = sorted(fams, key=lambda f: np.mean([per[s][f] for s, _, _ in PAIR]))

    # Stack the panels so the family-level result and the paired contrast are
    # both readable at full thesis width.
    fig, (axa, axb) = plt.subplots(
        2, 1, figsize=(FULLW, 6.25), sharey=True)
    colors = {"ppo_rom": "#2F6B95", "ppo_id_fd": "#D5A11E"}
    labels = {"ppo_rom": "R (PPO-ROM)", "ppo_id_fd": "IF (PPO-ID-FD)"}
    markers = {"ppo_rom": "o", "ppo_id_fd": "D"}
    y = np.arange(len(order))
    for i, f in enumerate(order):
        v = [per[s][f] for s, _, _ in PAIR]
        axa.plot([min(v), max(v)], [i, i], color="#CDD3D8", lw=1.8, zorder=1,
                 solid_capstyle="round")
    for s, _, _ in PAIR:
        axa.scatter([per[s][f] for f in order], y, s=43,
                    color=colors[s], marker=markers[s], zorder=3,
                    edgecolor="white", linewidth=.8, label=labels[s])
    axa.set_yticks(y)
    axa.set_yticklabels([f.replace("_", " ") for f in order], fontsize=9)
    axa.invert_yaxis()
    axa.set_xscale("log")
    axa.set_xticks([0.02, 0.05, 0.1, 0.2, 0.5])
    axa.set_xticklabels(["0.02", "0.05", "0.10", "0.20", "0.50"], fontsize=9)
    axa.xaxis.set_minor_formatter(plt.NullFormatter())
    axa.set_xlim(0.015, 0.95)
    axa.set_ylim(len(order) - 0.4, -1.35)      # headroom for the legend
    axa.set_xlabel("mean absolute lateral error (m)")
    axa.set_axisbelow(True)
    axa.grid(axis="x", color="#D5DADF", linewidth=.45, alpha=.65)
    axa.set_title("(a) lateral error by family, easiest first", loc="left")
    axa.legend(fontsize=8.4, loc="upper right", ncol=2, columnspacing=1.0,
               handletextpad=.4)

    d = 1000 * np.array([per["ppo_id_fd"][f] - per["ppo_rom"][f] for f in order])
    # Ten of the eleven differences are tens of millimetres; the eleventh is an
    # order of magnitude larger. A log axis would flatter the ten and a linear
    # one scaled to the eleventh would erase them, so the axis is set by the ten
    # and the outlier runs to the edge carrying its own value.
    lim = 92.0
    axb.barh(y, np.clip(d, -lim, lim),
             color=[colors["ppo_id_fd"] if v < 0 else colors["ppo_rom"]
                    for v in d], height=.58, alpha=.96)
    for i, v in enumerate(d):
        if abs(v) > lim:
            # Inside the bar, not beyond it: an off-scale label placed outside
            # the clipped end falls off the canvas.
            axb.annotate(f"{v:+.0f} mm", (np.sign(v) * lim, y[i]),
                         xytext=(6 if v < 0 else -6, 0),
                         textcoords="offset points", va="center",
                         ha="left" if v < 0 else "right", fontsize=7.4,
                         color="#1F2933" if v < 0 else "white",
                         weight="bold")
    axb.axvline(0, color="#3F464D", lw=1.0)
    axb.set_yticks(y)
    axb.set_yticklabels([f.replace("_", " ") for f in order], fontsize=9)
    axb.set_ylim(len(order) - 0.4, -1.35)
    axb.set_xlim(-lim * 1.05, lim * 1.05)
    axb.set_xticks([-75, 0, 75])
    axb.set_xlabel("IF $-$ R lateral error (mm)")
    axb.set_axisbelow(True)
    axb.grid(axis="x", color="#D5DADF", linewidth=.45, alpha=.65)
    better = int((d < 0).sum())
    axb.set_title(f"(b) IF lower on {better} of {len(order)} families", loc="left")
    for a in (axa, axb):
        for spine in a.spines.values():
            spine.set_color("#7C8791")
    fig.subplots_adjust(left=.205, right=.985, top=.94, bottom=.085, hspace=.30)
    save(fig, "ch7_e1_tracking")
    print(f"     ID-FD better on {better}, worse on {len(order) - better}")


