def fig_delay_response(amp=0.15):
    """When each stage of the chain actually starts moving, on one time axis.

    A normalised step response answers "what does the pressure do", not the
    question the section asks, which is "how long until each thing happens".
    This is that question drawn literally: the command edge is the origin, each
    downstream stage sits at its measured onset, and the bar beside it is the
    interquartile spread over command edges.
    """
    delays = load(OPENLOOP / "transport_delay.json")["links"]
    key = f"{amp}"
    chain = [("valve command", None, "#111111"),
             ("differential pressure", "command->dP", C_BLUE),
             ("cylinder extension", "command->cyl_ext", C_GREEN),
             ("joint angle", "command->joint_pos", C_PINK),
             ("cylinder velocity", "command->cyl_vel", C_ORANGE)]

    fig, ax = plt.subplots(figsize=(FULLW * 0.86, 2.95))
    xmax = 0.0
    for i, (label, k, col) in enumerate(chain):
        if k is None:
            ax.plot([0], [i], "|", ms=16, color=col, mew=2.4, zorder=4)
            ax.annotate("edge at $t = 0$", (0, i), xytext=(9, 0),
                        textcoords="offset points", va="center", fontsize=8.4)
            continue
        rec = delays[k][key]
        med = rec["median_ms"]
        q1, q3 = np.array(rec["iqr_steps"]) * 1000.0 / FS
        xmax = max(xmax, q3)
        ax.plot([0, med], [i, i], color=col, lw=6.5, alpha=.22,
                solid_capstyle="butt", zorder=1)
        ax.plot([q1, q3], [i, i], color=col, lw=2.0, zorder=3,
                solid_capstyle="round")
        ax.plot([med], [i], "o", ms=8.5, color=col, mec="white", mew=1.1,
                zorder=5)
        ax.annotate(f"{med:.0f} ms", (med, i), xytext=(0, 11),
                    textcoords="offset points", ha="center", fontsize=8.6,
                    color=col)
    ax.axvline(0, color="#111111", lw=1.3, zorder=2)
    ax.set_yticks(np.arange(len(chain)))
    ax.set_yticklabels([c[0] for c in chain], fontsize=9)
    ax.invert_yaxis()
    ax.set_xlim(-18, xmax * 1.10)
    ax.set_ylim(len(chain) - 0.30, -0.60)
    ax.set_xlabel("time after the valve command changes (ms)")
    ax.grid(axis="x")
    # Its own band below the last row. An annotation that hangs off the canvas,
    # or lands on a data row, is worse than none; both happened earlier.
    ax.annotate("shaded: the wait before that stage moves    "
                "bar: interquartile range over command edges",
                xy=(xmax * 1.08, len(chain) - 0.52), ha="right", va="center",
                fontsize=7.2, color="#6B7780")
    fig.subplots_adjust(left=.235, right=.98, top=.965, bottom=.185)
    save(fig, "ch7_delay_response")


def fig_delay_summary():
    """Onset delay by link and excitation amplitude; the control is the pair
    of links that must coincide."""
    d = load(OPENLOOP / "transport_delay.json")["links"]
    order = [("command$\\rightarrow$pressure", "command->dP", C_BLUE),
             ("pressure$\\rightarrow$velocity", "dP->cyl_vel", C_ORANGE),
             ("command$\\rightarrow$extension", "command->cyl_ext", C_GREEN),
             ("command$\\rightarrow$joint", "command->joint_pos", C_PINK)]
    amps = sorted({float(a) for k in d for a in d[k]})
    fig, ax = plt.subplots(figsize=(FULLW * 0.66, 2.6))
    w, x = 0.2, np.arange(len(amps))
    for i, (label, key, col) in enumerate(order):
        vals = [d[key].get(f"{a:g}", {}).get("median_ms", np.nan) for a in amps]
        ax.bar(x + (i - 1.5) * w, vals, width=w, color=col, label=label, alpha=.9)
    ax.set_xticks(x)
    ax.set_xticklabels([f"{a:g}" for a in amps])
    ax.set_xlabel("excitation amplitude")
    ax.set_ylabel("median onset delay (ms)")
    ax.set_ylim(0, 250)
    ax.grid(axis="y")
    ax.legend(fontsize=7, ncol=2, loc="upper center")
    fig.subplots_adjust(left=.135, right=.98, top=.965, bottom=.19)
    save(fig, "ch7_delay_summary")


def fig_chain_by_stack():
    """Closed-loop chain latency, matched pair.

    Cross-correlation lag, not onset: a closed-loop command has no step edges.
    Valid for comparing stacks, where the bias is identical, and not comparable
    with the open-loop dead times.
    """
    d = load(EXP / "E2/results/chain_delay_by_stack.json")["stacks"]
    links = ["command $\\to$ pressure", "pressure $\\to$ cyl. velocity",
             "command $\\to$ cyl. velocity", "cyl. velocity $\\to$ joint velocity"]
    nice = ["command $\\rightarrow$ pressure", "pressure $\\rightarrow$ cyl. velocity",
            "command $\\rightarrow$ cyl. velocity",
            "cyl. velocity $\\rightarrow$ joint velocity"]
    fig, ax = plt.subplots(figsize=(FULLW * 0.92, 2.9))
    colors = {"ppo_rom": "#2F6B95", "ppo_id_fd": "#D5A11E"}
    labels_by_stack = {"ppo_rom": "R (PPO-ROM)",
                       "ppo_id_fd": "IF (PPO-ID-FD)"}
    y = np.arange(len(links))
    h = 0.3
    step_ms = 1000.0 / FS
    # The mechanical link is the control: a static linkage cannot delay, so the
    # row must read the resolution floor of one control step. Shade that row and
    # say what the floor is, rather than claiming it must read zero.
    ax.axhspan(len(links) - 1 - 0.5, len(links) - 1 + 0.5, color="#F1F4F6", lw=0,
               zorder=0)
    for i, (s, _, _) in enumerate(PAIR):
        vals = [d[JSON_KEY[s]][k]["median_ms"] for k in links]
        ax.barh(y + (i - 0.5) * h, vals, height=h * 0.84,
                color=colors[s], alpha=.97, label=labels_by_stack[s], zorder=2)
        for j, v in enumerate(vals):
            ax.annotate(f"{v:.0f}", (max(v, 0), y[j] + (i - 0.5) * h),
                        xytext=(5, 0),
                        textcoords="offset points", va="center", fontsize=7.8,
                        color="#3F464D", zorder=3)
    ax.axvline(step_ms, color="#7C8791", lw=1.0, ls=":", zorder=1)
