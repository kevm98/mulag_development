def _boot(d, n=4000, seed=11):
    import random
    rng = random.Random(seed)
    m = len(d)
    out = sorted(sum(d[rng.randrange(m)] for _ in range(m)) / m for _ in range(n))
    return out[int(0.025 * n)], out[int(0.975 * n)]


